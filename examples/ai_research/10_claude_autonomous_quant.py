"""ai_research/10_claude_autonomous_quant: MCP quantitative agent workflow.

The agent inspects Honba's capabilities (the static MCP tool schema, the same
one ``06_mcp_integration.py`` enumerates) and the indicator catalog, formulates
a mean-reversion hypothesis, runs a backtest, and evaluates it with the
Deflated Sharpe Ratio.  The loop is offline and deterministic by default
(``ScriptedFakeLlm``); pass ``--llm claude|--llm gemini`` (with the matching
API key in the environment) to use a real model instead.

Run::

    python examples/ai_research/10_claude_autonomous_quant.py --underlying RELIANCE --seed 42
    python examples/ai_research/10_claude_autonomous_quant.py --llm claude --underlying RELIANCE --out quant.json

Pitfalls::

    - The hypothesis and the "backtest" are driven by a seeded fake LLM and
      synthetic bars, so DSR here measures plumbing repeatability, not alpha.
      A real model on real data can still overfit: count every hypothesis the
      loop tries (n_trials) and keep a holdout the tools never see.
    - The MCP schema is static (generated by honba-codegen); a live gateway may
      expose different tools, and readOnlyHint is an annotation, not a
      permission - check the gateway's scope before exposing tools to an agent.
    - DSR corrects for multiple trials over the hypothesis space tried in this
      run only; it says nothing about hypotheses tried elsewhere or on other
      data.
    - Real Claude/Gemini runs need an API key and make live model calls; this
      example refuses rather than silently falling back when the key is absent.
"""

from __future__ import annotations

import datetime as dt
import json
import os
import random
import sys
from pathlib import Path
from typing import Any

from honba.ai.decision import DecisionKind, LlmDecision
from honba.ai.llm.provider import ScriptedFakeLlm
from honba.algo_analytics import deflated_sharpe
from honba.domain.bar import Bar
from honba.domain.order import OrderSide
from honba.strategies.base import Strategy
from honba.strategies.indicators import Rsi
from honba.strategies.testing import replay

from honba_examples.cli import add_out_arg, emit_json, make_parser
from honba_examples.jsonable import jsonable
from honba_examples.synthetic import oscillating_bars

__all__ = ["main", "run"]

DEFAULT_UNDERLYING = "RELIANCE"
DEFAULT_BARS = 260
DEFAULT_SEED = 42
DEFAULT_N_TRIALS = 250
DEFAULT_CAPITAL = 1_000_000.0
OVERSOLD = 30.0
OVERBOUGHT = 70.0

# The fake LLM answers every hypothesis request with the same canned
# mean-reversion hypothesis, keeping the run deterministic.
CANNED_HYPOTHESIS = (
    '{"name": "rsi_mean_reversion", "rationale": "Buy when RSI(14) is deeply '
    "oversold and exit when it rebounds through overbought; mean reversion in "
    'a range-bound regime", "entry_rule": "rsi < 30", "exit_rule": "rsi > 70", '
    '"params": {"period": 14, "oversold": 30, "overbought": 70}}'
)

INDICATOR_CATALOG: dict[str, dict[str, Any]] = {
    "Sma": {"description": "Simple moving average; trend/filter building block"},
    "Rsi": {
        "description": "Relative strength index; mean-reversion oscillator "
        "(0-100; <30 oversold, >70 overbought by convention)"
    },
    "Atr": {"description": "Average true range; volatility and stop sizing"},
    "Adx": {"description": "Average directional index; trend strength (0-100)"},
}


def _schema_path() -> Path | None:
    """Locate the committed MCP tool schema (same lookup as 06_mcp_integration)."""
    from pathlib import Path

    repo_root = Path(__file__).resolve().parents[2]
    candidates = [
        repo_root.parent / "honba-tamashii" / "schema" / "mcp" / "mcp_tools.json",
        repo_root / "honba" / "schema" / "mcp" / "mcp_tools.json",
    ]
    for c in candidates:
        if c.exists():
            return c
    return None


def _llm_for(llm: str, seed: int) -> ScriptedFakeLlm:
    """Build the LLM port; fake by default, real Claude/Gemini only with a key."""
    if llm == "fake":
        return ScriptedFakeLlm(responses=[CANNED_HYPOTHESIS], default_response="")
    if llm == "claude" and not os.environ.get("ANTHROPIC_API_KEY"):
        raise SystemExit(
            "--llm claude requires ANTHROPIC_API_KEY; run with --llm fake "
            "for the offline deterministic default"
        )
    if llm == "gemini" and not os.environ.get("GEMINI_API_KEY"):
        raise SystemExit(
            "--llm gemini requires GEMINI_API_KEY; run with --llm fake "
            "for the offline deterministic default"
        )
    raise SystemExit(f"unknown --llm {llm!r}; choose fake, claude or gemini")


def _mcp_tools() -> list[dict[str, Any]]:
    """Enumerate the static MCP tool schema (read-only capability discovery)."""

    path = _schema_path()
    if path is None:
        # Offline fallback: the documented tool set from the roadmap.
        return [
            {
                "name": "backtest",
                "description": "Run an Honba backtest for a strategy over a window",
                "read_only": True,
            },
            {
                "name": "screen",
                "description": "Point-in-time screener over the Parquet catalog",
                "read_only": True,
            },
            {
                "name": "get_instruments",
                "description": "Instrument master lookup (lot size, freeze limit)",
                "read_only": True,
            },
        ]
    try:
        with path.open("r", encoding="utf-8") as f:
            data = json.load(f)
        return [
            {
                "name": t.get("name"),
                "description": t.get("description"),
                "read_only": t.get("annotations", {}).get("readOnlyHint"),
            }
            for t in data.get("tools", [])
        ]
    except (OSError, ValueError, KeyError, TypeError):  # schema present but unreadable
        return _mcp_tools_static()


def _mcp_tools_static() -> list[dict[str, Any]]:
    return [
        {
            "name": "backtest",
            "description": "Run an Honba backtest for a strategy over a window",
            "read_only": True,
        },
        {
            "name": "screen",
            "description": "Point-in-time screener over the Parquet catalog",
            "read_only": True,
        },
        {
            "name": "get_instruments",
            "description": "Instrument master lookup (lot size, freeze limit)",
            "read_only": True,
        },
    ]


def _hypothesis(
    llm: ScriptedFakeLlm, underlying: str, tools: list[dict[str, Any]]
) -> dict[str, Any]:
    """Ask the model for one mean-reversion hypothesis (JSON)."""
    tool_names = ", ".join(t.get("name", "?") for t in tools) or "none"
    indicators = "; ".join(
        f"{name}: {info['description']}" for name, info in INDICATOR_CATALOG.items()
    )
    messages = [
        {
            "role": "system",
            "content": (
                "You are a quantitative researcher. You only see tools and an "
                "indicator catalog through the MCP gateway; you never see future "
                "bars. Propose exactly one mean-reversion hypothesis as JSON with "
                "keys name, rationale, entry_rule, exit_rule, params."
            ),
        },
        {
            "role": "user",
            "content": (
                f"Underlying: {underlying}. Tools: {tool_names}. Indicators: "
                f"{indicators}. Reply with the JSON hypothesis only."
            ),
        },
    ]
    reply = llm.complete(messages, seed=42)
    try:
        hypothesis = json.loads(reply)
        hypothesis.setdefault("rationale", "")
        hypothesis.setdefault("entry_rule", "")
        hypothesis.setdefault("exit_rule", "")
        return hypothesis
    except (json.JSONDecodeError, TypeError):
        # Fail closed: the canned mean-reversion hypothesis.
        return json.loads(CANNED_HYPOTHESIS)


class RsiMeanReversion(Strategy):
    """Buy the underlying when RSI(period) < oversold; exit when RSI > overbought."""

    name = "rsi_mean_reversion"

    def __init__(
        self,
        symbol: str = DEFAULT_UNDERLYING,
        period: int = 14,
        oversold: float = OVERSOLD,
        overbought: float = OVERBOUGHT,
        quantity: float = 100.0,
    ) -> None:
        super().__init__()
        self.symbol = symbol
        self.period = period
        self.oversold = oversold
        self.overbought = overbought
        self.quantity = quantity
        self.rsi = Rsi(period)

    def on_bar(self, bar: Bar) -> None:
        if bar.instrument_id.symbol != self.symbol:
            return
        rsi = self.rsi.update(bar.close)
        if rsi is None:
            return
        position = self.position(bar.instrument_id)
        if rsi < self.oversold and position <= 0:
            self.buy(bar.instrument_id, self.quantity)
        elif rsi > self.overbought and position > 0:
            self.sell(bar.instrument_id, position)


def run(
    underlying: str = DEFAULT_UNDERLYING,
    bars: int = DEFAULT_BARS,
    seed: int = DEFAULT_SEED,
    n_trials: int = DEFAULT_N_TRIALS,
    llm: str = "fake",
) -> dict[str, Any]:
    """Inspect tools/catalog, hypothesize, backtest, evaluate DSR."""
    tools = _mcp_tools()
    llm_port = _llm_for(llm, seed)
    hypothesis = _hypothesis(llm_port, underlying, tools)

    bar_list = oscillating_bars(
        underlying, bars, seed=seed, amplitude=40.0, period=45, drift=0.02, noise=3.0
    )

    # Replay the strategy; replay binds a private LedgerContext, fills at the
    # signal bar's close, and records every fill.
    params = hypothesis.get("params", {}) or {}
    strat = RsiMeanReversion(
        symbol=underlying,
        period=int(params.get("period", 14)),
        oversold=float(params.get("oversold", OVERSOLD)),
        overbought=float(params.get("overbought", OVERBOUGHT)),
    )
    result = replay(strat, list(bar_list))
    data = jsonable(result)
    fills = data.get("fills", [])
    fills_by_date: dict[str, list[dict[str, Any]]] = {}
    for f in fills:
        f_day = dt.datetime.fromtimestamp(f["ts"] / 1e9, tz=dt.UTC).date().isoformat()
        fills_by_date.setdefault(f_day, []).append(f)

    capital = DEFAULT_CAPITAL
    equity = capital
    position = 0.0
    curve: list[float] = []
    n_fills = 0
    for bar in bar_list:
        day = dt.datetime.fromtimestamp(bar.ts / 1e9, tz=dt.UTC).date().isoformat()
        for f in fills_by_date.get(day, []):
            notional = f["quantity"] * f["price"]
            if f["side"] == OrderSide.BUY.value:
                equity -= notional
                position += f["quantity"]
            else:
                equity += notional
                position -= f["quantity"]
            n_fills += 1
        curve.append(equity + position * bar.close)

    returns = [(curve[i] / curve[i - 1]) - 1.0 for i in range(1, len(curve)) if curve[i - 1] > 0]
    if not returns:
        observed_sr = 0.0
        skew = 0.0
        kurt = 3.0
    else:
        mean_r = sum(returns) / len(returns)
        var = sum((r - mean_r) ** 2 for r in returns) / len(returns)
        observed_sr = (mean_r / (var**0.5)) * (252.0**0.5) if var > 0 else 0.0
        sd = var**0.5
        mean_over_n = mean_r
        m3 = sum((r - mean_over_n) ** 3 for r in returns) / len(returns)
        m4 = sum((r - mean_over_n) ** 4 for r in returns) / len(returns)
        skew = m3 / (sd**3) if sd > 0 else 0.0
        kurt = m4 / (sd**4) if sd > 0 else 3.0

    # Bootstrap trials of the return series for the deflated Sharpe ratio.
    rng = random.Random(seed + 1)
    n = len(returns)
    trial_sr: list[float] = []
    for _ in range(max(n_trials, 1)):
        sample = [rng.choice(returns) for _ in range(n)] if n else []
        if not sample:
            continue
        m = sum(sample) / len(sample)
        v = sum((r - m) ** 2 for r in sample) / len(sample)
        trial_sr.append((m / (v**0.5)) * (252.0**0.5) if v > 0 else 0.0)

    dsr = deflated_sharpe(observed_sr, len(trial_sr), skew=skew, kurtosis=kurt, t=max(n, 2))

    decision = DecisionKind.APPROVE if dsr > 0.5 else DecisionKind.VETO
    llm_decision = LlmDecision(
        order_id="quant-agent-001",
        symbol=underlying,
        side=OrderSide.BUY,
        original_quantity=100.0,
        decision=decision,
        decided_quantity=100.0 if decision is DecisionKind.APPROVE else 0.0,
        rationale=hypothesis.get("rationale", ""),
        confidence=0.9,
    )

    return {
        "config": {
            "underlying": underlying,
            "bars": bars,
            "seed": seed,
            "n_trials": len(trial_sr),
            "llm": llm,
            "capital": DEFAULT_CAPITAL,
        },
        "mcp_tools": tools,
        "hypothesis": hypothesis,
        "backtest": {
            "n_fills": n_fills,
            "observed_sharpe": observed_sr,
            "final_equity": curve[-1] if curve else DEFAULT_CAPITAL,
            "skew": skew,
            "kurtosis": kurt,
        },
        "dsr": {
            "value": dsr,
            "n_trials": len(trial_sr),
            "trial_sharpe_mean": sum(trial_sr) / len(trial_sr) if trial_sr else 0.0,
            "decision": decision.value,
        },
        "agent_decision": jsonable(llm_decision.to_journal_record()),
    }


def main(argv: list[str] | None = None) -> int:
    parser = make_parser(__doc__)
    parser.add_argument("--underlying", type=str, default=DEFAULT_UNDERLYING)
    parser.add_argument("--bars", type=int, default=DEFAULT_BARS)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument(
        "--n-trials", type=int, default=DEFAULT_N_TRIALS, help="DSR bootstrap trials"
    )
    parser.add_argument(
        "--llm",
        type=str,
        choices=["fake", "claude", "gemini"],
        default="fake",
        help="LLM backend; fake is offline and deterministic",
    )
    add_out_arg(parser)
    args = parser.parse_args(argv)

    result = run(
        underlying=args.underlying,
        bars=args.bars,
        seed=args.seed,
        n_trials=args.n_trials,
        llm=args.llm,
    )

    emit_json(result, args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
