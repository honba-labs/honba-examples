"""ai_research/06_mcp_integration: enumerate the MCP gateway's static tool schema.

The MCP gateway exposes Honba's read-only capabilities as Model Context Protocol
tools. The schema is generated by the Rust codegen (`honba-codegen`) into
``schema/mcp/mcp_tools.json`` at build time — no server needs to run and no
real LLM is required to discover what tools exist. This example loads that
schema and reports the six tools with their names, descriptions, input/output
schemas, and the ``readOnlyHint`` annotation.

This is the offline, scaffold-only variant. The live gateway (`honba mcp serve`,
P1 in the roadmap) would host these same six tools over stdio/HTTP, backed by
the Rust HTTP API (`honba-api-rest`).

Run::

    python ai_research/06_mcp_integration.py
    python ai_research/06_mcp_integration.py --out mcp_tools.json

Pitfalls::

    - Prose drift: the text above and the README say six tools, but the schema in the honba
      checkout lists 11 today. Trust tool_count in the output, and note the schema is read from
      the sibling honba checkout (schema_path), so a different checkout lists different tools.
    - readOnlyHint is a hint, not a permission: every tool is annotated read-only, including
      backtest, sweep and compile_strategy, which run heavy computations. This script
      only reports the annotation; whether a gateway enforces the scope (research, read:market)
      is not shown here, so check it before exposing a tool to an agent.
    - Nothing is called: a static schema says nothing about the safety of tool outputs. Text a
      tool returns (screen results, bars, journals, strategy names) and the tool descriptions
      themselves are read by the model, so both are prompt-injection channels. Review descriptions.
    - Agents multiply trials: an agent looping over backtest and sweep tools is a parameter search
      in disguise. Count every call as a trial and keep a holdout the tools cannot see.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # plain checkout: no editable install

from honba_examples.cli import add_out_arg, emit_json, make_parser
from honba_examples.jsonable import jsonable


def _schema_path() -> Path:
    """Locate the committed MCP schema: schema/mcp/mcp_tools.json, generated by
    honba-codegen, relative to this repo's sibling in honba-workspace.
    """
    # This repo: honba-workspace/honba-examples/
    # In-workspace home of the Python `honba` package: honba-workspace/honba-tamashii/
    repo_root = Path(__file__).resolve().parents[1]
    candidates = [
        repo_root.parent / "honba-tamashii" / "schema" / "mcp" / "mcp_tools.json",
        # Legacy stopgap location (honba-labs, outside the workspace via the old
        # honba-workspace/honba symlink) — kept only as a fallback during cutover.
        repo_root.parent / "honba" / "schema" / "mcp" / "mcp_tools.json",
        repo_root / "honba" / "schema" / "mcp" / "mcp_tools.json",
    ]
    for c in candidates:
        if c.exists():
            return c
    raise FileNotFoundError(
        "MCP schema not found. Expected at ../honba-tamashii/schema/mcp/mcp_tools.json "
        "relative to this repo, or run `make mcp` in the honba-tamashii checkout."
    )


def run() -> dict[str, Any]:
    """Load the MCP tool schema and return a JSON-serializable summary."""
    path = _schema_path()
    with path.open("r", encoding="utf-8") as f:
        data = json.load(f)

    tools = data.get("tools", [])
    summary = {
        "schema_path": str(path),
        "comment": data.get("$comment"),
        "tool_count": len(tools),
        "tools": [
            {
                "name": t.get("name"),
                "description": t.get("description"),
                "read_only": t.get("annotations", {}).get("readOnlyHint"),
                "input_schema": jsonable(t.get("inputSchema")),
                "output_schema": jsonable(t.get("outputSchema")),
            }
            for t in tools
        ],
    }
    return summary


def main(argv: list[str] | None = None) -> int:
    parser = make_parser(__doc__)
    add_out_arg(parser)
    args = parser.parse_args(argv)

    result = run()

    emit_json(result, args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
